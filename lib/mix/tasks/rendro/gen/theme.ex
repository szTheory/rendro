defmodule Mix.Tasks.Rendro.Gen.Theme do
  @moduledoc """
  Generates an application-owned, fixed Rendro theme wrapper.

      mix rendro.gen.theme PRESET --accent #RRGGBB [--mode light|dark]
        [--module Elixir.Module.Name] [--out lib/path/to/theme.ex] [--force | --check]

  `PRESET`, `--accent`, and `--mode` use Rendro's closed vocabulary. The generated
  module intentionally exposes only `theme/0` and `register_fonts/1`; edit the
  committed wrapper if the application later needs a different policy. Re-running
  this task does not update detached application code.

  Normal writes use Mix's standard conflict handling. `--force` is the sole
  noninteractive overwrite path. `--check` only compares bytes and never creates,
  prompts for, or writes files. These are single-invocation guarantees; this task
  makes no parallel-writer or interruption-rollback claim.
  """
  @moduledoc tags: [:adapter]
  @shortdoc "Generate a fixed, application-owned Rendro theme wrapper"

  use Mix.Task

  alias Rendro.Theme.Snippet

  @presets ~w(swiss humanist editorial corporate-classic minimal-mono brutalist)
  @accents ~w(#0E7C76 #147A4B #1F4FB8 #2C6BED #6E3CB8 #C24132 #C78600)
  @modes ~w(light dark)
  @default_accent "#2C6BED"

  @impl Mix.Task
  def run(args) do
    args
    |> parse!()
    |> generate!()
  end

  defp parse!(args) do
    {options, positionals, invalid} =
      OptionParser.parse(args,
        strict: [
          accent: :string,
          mode: :string,
          module: :string,
          out: :string,
          force: :boolean,
          check: :boolean
        ]
      )

    if invalid != [] do
      fail!("option", inspect(invalid), "unknown or malformed option")
    end

    preset =
      case positionals do
        [value] -> value
        [] -> fail!("preset", "missing", "exactly one positional preset is required")
        values -> fail!("preset", inspect(values), "only one positional preset is accepted")
      end

    accent =
      Keyword.get(options, :accent) || fail!("accent", "missing", "--accent #RRGGBB is required")

    mode = Keyword.get(options, :mode, "light")

    validate_member!("preset", preset, @presets)
    validate_member!("accent", accent, @accents)
    validate_member!("mode", mode, @modes)

    if Keyword.get(options, :force, false) and Keyword.get(options, :check, false) do
      fail!("flags", "--force --check", "--force and --check are mutually exclusive")
    end

    module = Keyword.get_lazy(options, :module, &default_module!/0)
    validate_module!(module)

    out = Keyword.get_lazy(options, :out, fn -> default_out(module) end)
    validate_out!(out)

    %{
      preset: preset,
      accent: accent,
      mode: mode,
      module: module,
      out: out,
      force?: Keyword.get(options, :force, false),
      check?: Keyword.get(options, :check, false)
    }
  end

  defp generate!(config) do
    source = source(config)

    if config.check? do
      check!(config, source)
    else
      case Mix.Generator.create_file(config.out, source,
             format_elixir: true,
             force: config.force?
           ) do
        true -> Mix.shell().info("Generated #{config.out}. Re-run: #{rerun(config)}")
        false -> Mix.shell().info("Skipped #{config.out}. Re-run: #{rerun(config)}")
      end
    end
  end

  defp source(config) do
    ("# Generated by: #{rerun(config)}\n" <>
       Snippet.module_source(config.module, config.preset, config.accent, config.mode))
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp check!(config, source) do
    case File.read(config.out) do
      {:ok, ^source} ->
        Mix.shell().info("rendro.gen.theme --check: OK — #{config.out} matches #{rerun(config)}")

      {:ok, _existing} ->
        fail!("output", config.out, "bytes differ from the generated wrapper", config)

      {:error, :enoent} ->
        fail!("output", config.out, "file is missing", config)

      {:error, reason} ->
        fail!("output", config.out, "cannot read file: #{:file.format_error(reason)}", config)
    end
  end

  defp default_module! do
    case Mix.Project.config()[:app] do
      app when is_atom(app) ->
        namespace = app |> Atom.to_string() |> Macro.camelize()

        if valid_alias_segment?(namespace) do
          "#{namespace}.RendroTheme"
        else
          fail!("application namespace", inspect(app), "cannot derive a safe Elixir module alias")
        end

      value ->
        fail!(
          "application namespace",
          inspect(value),
          "Mix project :app must be an atom to derive a module"
        )
    end
  end

  defp default_out(module) do
    relative =
      module
      |> String.split(".")
      |> Enum.map(&Macro.underscore/1)
      |> Path.join()

    Path.join("lib", relative <> ".ex")
  end

  defp validate_member!(resource, value, allowed) do
    if value in allowed do
      :ok
    else
      fail!(resource, inspect(value), "must be one of #{Enum.join(allowed, ", ")}")
    end
  end

  defp validate_module!(module) when is_binary(module) do
    segments = String.split(module, ".", trim: true)

    if segments != [] and Enum.join(segments, ".") == module and
         Enum.all?(segments, &valid_alias_segment?/1) do
      :ok
    else
      fail!("module", inspect(module), "must be a dot-separated Elixir alias with safe segments")
    end
  end

  defp validate_module!(module),
    do: fail!("module", inspect(module), "must be a string Elixir alias")

  defp valid_alias_segment?(segment) do
    Regex.match?(~r/^[A-Z][A-Za-z0-9_]*$/, segment)
  end

  defp validate_out!(out) when is_binary(out) do
    segments = String.split(out, ["/", "\\\\"], trim: false)

    if out != "" and Path.type(out) != :absolute and
         Enum.all?(segments, &(&1 not in ["", ".", ".."])) do
      :ok
    else
      fail!("output path", inspect(out), "must be a safe relative path without parent traversal")
    end
  end

  defp validate_out!(out),
    do: fail!("output path", inspect(out), "must be a relative path string")

  defp rerun(config) do
    "mix rendro.gen.theme #{config.preset} --accent #{config.accent} --mode #{config.mode}" <>
      optional_switch("--module", config.module, default_module!()) <>
      optional_switch("--out", config.out, default_out(config.module))
  end

  defp optional_switch(_flag, value, value), do: ""
  defp optional_switch(flag, value, _default), do: " #{flag} #{value}"

  defp fail!(resource, value, reason, config \\ nil) do
    rerun =
      if config,
        do: rerun(config),
        else: "mix rendro.gen.theme swiss --accent #{@default_accent} --mode light"

    Mix.raise("Invalid #{resource} #{value}: #{reason}. Next: #{rerun}")
  end
end
